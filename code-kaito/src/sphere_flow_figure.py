"""Publication panels from the pinned sphere ODE; no fitted or schematic paths."""
from pathlib import Path
import sys
import json
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.patches import Circle
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'vendor/latent-equivariant/code/examples'))
import sphere_geometry as geom
import figure_style as style

ELEV=np.deg2rad(18)
D=np.array([np.cos(ELEV),0,np.sin(ELEV)])
U=np.array([0,1,0]);W=np.cross(D,U)
COLORS={'S':style.morse(1),'T-':style.morse(0),'E':style.morse(3),'T+':style.morse(2),'N':style.morse(4)}
RC={'font.family':'serif','font.serif':['STIXGeneral'],'mathtext.fontset':'stix','font.size':10,
    'axes.linewidth':.65,'axes.spines.top':False,'axes.spines.right':False,'pdf.fonttype':42,'svg.fonttype':'none'}
def project(p):return p@U,p@W,p@D

def curve(ax,p,color,lw=1,ls='-',rear=True):
    x,y,d=project(p)
    for front in (False,True):
        if not front and not rear:continue
        mask=d>=0 if front else d<0
        for a,b in geom.split_runs(mask):
            ax.plot(x[a:b],y[a:b],color=color,lw=lw if front else .65,ls=ls,
                    alpha=1 if front else .22,zorder=4 if front else 1)

def sphere(ax, show_trajectories=True):
    ax.set(aspect='equal',xlim=(-1.12,1.35),ylim=(-1.16,1.17));ax.axis('off')
    ax.add_patch(Circle((0,0),1,facecolor='#fafafa',edgecolor='.63',lw=.65,zorder=0))
    for z,key in [(-.4,'T-'),(0,'E'),(.4,'T+')]:
        curve(ax,geom.latitude(z,1001),COLORS[key],1.35,'--' if z==0 else '-')
    # Each short segment starts on the front hemisphere and follows the actual ODE.
    for z,phi in ([(.79,-.65),(.18,-.65),(-.18,.0),(-.79,-.5)] if show_trajectories else []):
        p=geom.trajectory(z,phi,t_max=2.3)
        curve(ax,p,'.36',.75,rear=False)
        x,y,d=project(p);i=int(.65*(len(p)-1));j=min(i+9,len(p)-1)
        if min(d[i],d[j])>0:
            ax.annotate('',xy=(x[j],y[j]),xytext=(x[i],y[i]),zorder=5,
                        arrowprops={'arrowstyle':'-|>','color':'.36','lw':.8,'mutation_scale':8,'shrinkA':0,'shrinkB':0})
    for z,key in [(1,'N'),(-1,'S')]:
        x,y,d=project(np.array([0.,0.,z]));back=d<0
        ax.plot(x,y,'o',ms=4,mfc='white',mec=COLORS[key],mew=1,alpha=.45 if back else 1,zorder=5)
        ax.text(0,1.08*z,'$'+key+'$',ha='center',va='center',color=COLORS[key])
    for z,key,label in [(.4,'T+',r'$A_+$'),(0,'E','$C$'),(-.4,'T-',r'$A_-$')]:
        ax.text(1.10,z*np.cos(ELEV),label,ha='left',va='center',color=COLORS[key])

def height(ax):
    # Endpoint refinement resolves the high slope of h_3 near the repelling poles.
    z=np.unique(np.r_[np.linspace(-1,1,1401),1-10.**(-np.linspace(1,12,300)),-1+10.**(-np.linspace(1,12,300)),-.4,.4])
    h=geom.hmap(z,3)
    assert np.min(np.diff(h))>=-1e-10
    assert np.max(np.abs(geom.hmap(np.array([-1,-.4,0,.4,1]),3)-[-1,-.4,0,.4,1]))<1e-12
    ax.plot([-1,1],[-1,1],color='.83',lw=.85,zorder=0)
    ax.plot(z,h,color='.16',lw=1.25)
    for a,key in [(-1,'S'),(-.4,'T-'),(0,'E'),(.4,'T+'),(1,'N')]:
        ax.plot(a,a,'o',ms=4.6,mec=COLORS[key],mfc=COLORS[key] if abs(a)==.4 else 'white',mew=1,zorder=5)
    ax.set(aspect='equal',xlim=(-1.07,1.07),ylim=(-1.07,1.07),xlabel='$z$',ylabel='$h_3(z)$')
    ax.set_xticks([-1,-.4,0,.4,1],['$-1$',r'$-z_t$','$0$',r'$z_t$','$1$'])
    ax.set_yticks([-1,0,1]);ax.tick_params(length=3,width=.65,pad=3)

def render():
    out=ROOT/'artifacts/sphere-flow';out.mkdir(parents=True,exist_ok=True)
    with plt.rc_context(RC):
        fig=plt.figure(figsize=(6,2.85))
        left=fig.add_axes([.015,.12,.455,.77]);right=fig.add_axes([.60,.16,.355,.745])
        sphere(left);height(right)
        for ext in ['pdf','svg','png']:fig.savefig(out/f'sphere-flow-comparison.{ext}',dpi=220,bbox_inches='tight',pad_inches=.035)
        plt.close(fig)
        for name,draw in [('sphere',sphere),('height-map',height)]:
            fig,ax=plt.subplots(figsize=(2.8,2.7));draw(ax)
            for ext in ['pdf','svg','png']:fig.savefig(out/f'{name}.{ext}',dpi=220,bbox_inches='tight',pad_inches=.035)
            plt.close(fig)
    (out/'README.md').write_text('''# Sphere flow and height map

Generated by `code-kaito/src/sphere_flow_figure.py`, using the pinned
`sphere_geometry.py`: C=1, z_t=0.4, omega=0.6, map time=3.
Orthographic transparent view at elevation 18 degrees; rear orbit segments
and the rear South pole are faint. Gray arrows follow numerically integrated
trajectories. Filled height-map markers denote attracting fixed points;
open markers denote repelling fixed points. The gray diagonal is the identity.
The original manuscript and upstream renderer are unchanged.
''')
    return out
if __name__=='__main__':print(render())
